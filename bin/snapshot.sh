#!/usr/bin/env bash
# ==============================================================================
# ⏪ FREEBUFF-POWER SUPREME TIME-TRAVEL SNAPSHOTS & 1-SECOND INSTANT ROLLBACK
# Supports Git Checkpoint Stash/Branches + Tar Archive Fallback (Anti-Nyesel Mode)
# ==============================================================================
set -euo pipefail

C_CYAN='\033[0;36m'
C_GREEN='\033[0;32m'
C_YELLOW='\033[0;33m'
C_RED='\033[0;31m'
C_BOLD='\033[1m'
C_DIM='\033[2m'
C_RESET='\033[0m'

SNAPSHOT_DIR=".freebuff-snapshots"
mkdir -p "$SNAPSHOT_DIR"

IS_GIT_REPO=false
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  IS_GIT_REPO=true
fi

function save_snapshot() {
  local label="${*:-auto_checkpoint_$(date +%Y%m%d_%H%M%S)}"
  local timestamp
  timestamp="$(date +%Y%m%d_%H%M%S)"
  local clean_label="${label// /_}"
  local checkpoint_name="freebuff_cp_${timestamp}_${clean_label}"

  if [ "$IS_GIT_REPO" = true ]; then
    # Git-native Instant Tree Snapshot (Under 0.2s without heavy disk writes)
    local current_branch
    current_branch="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo 'detached')"
    
    # Save uncommitted changes to a temporary git commit/stash tree
    git stash create > "$SNAPSHOT_DIR/last_stash_sha" 2>/dev/null || true
    local stash_sha
    stash_sha="$(cat "$SNAPSHOT_DIR/last_stash_sha" 2>/dev/null || echo '')"
    
    # Also save git tag / lightweight branch ref
    git branch -f "$checkpoint_name" HEAD >/dev/null 2>&1 || true
    echo "$checkpoint_name" > "$SNAPSHOT_DIR/latest_git_checkpoint"
    echo "$stash_sha" > "$SNAPSHOT_DIR/${checkpoint_name}.stash"

    echo -e "${C_CYAN}📸 [Git Checkpoint] Disimpan: ${C_BOLD}$checkpoint_name${C_RESET} ${C_DIM}(Branch: $current_branch)${C_RESET}"
    echo -e "${C_GREEN}✅ Checkpoint aktif! Jika koding AI rusak, ketik: ${C_BOLD}freebuff-power rollback${C_RESET}"
  else
    # Fallback to Tar Archive for non-git folders
    local target_archive="$SNAPSHOT_DIR/${timestamp}_${clean_label}.tar.gz"
    echo -e "${C_CYAN}📸 [Archive Snapshot] Membuat cadangan: ${C_BOLD}$label${C_RESET}..."
    tar --exclude="$SNAPSHOT_DIR" --exclude="node_modules" --exclude=".git" --exclude=".next" --exclude=".cache" -czf "$target_archive" . 2>/dev/null || true
    echo -e "${C_GREEN}✅ Snapshot tersimpan: $target_archive${C_RESET}"
  fi
}

function restore_snapshot() {
  echo -e "${C_YELLOW}${C_BOLD}⏪ [FREEBUFF-POWER ROLLBACK] Memulihkan proyek ke kondisi sebelum disentuh AI...${C_RESET}"

  if [ "$IS_GIT_REPO" = true ] && [ -f "$SNAPSHOT_DIR/latest_git_checkpoint" ]; then
    local cp_name
    cp_name="$(cat "$SNAPSHOT_DIR/latest_git_checkpoint" 2>/dev/null || echo '')"

    if [ -n "$cp_name" ] && git rev-parse --verify "$cp_name" >/dev/null 2>&1; then
      echo -e "${C_CYAN}🔄 Memulihkan dari Git Checkpoint: ${C_BOLD}$cp_name${C_RESET}..."
      
      # Clean untracked files generated by AI
      git clean -fd -e "$SNAPSHOT_DIR" 2>/dev/null || true
      
      # Reset working directory back to checkpoint commit
      git reset --hard "$cp_name" 2>/dev/null || true

      # If there was an uncommitted stash tree when snapshot was taken, restore it
      local stash_file="$SNAPSHOT_DIR/${cp_name}.stash"
      if [ -f "$stash_file" ]; then
        local stash_sha
        stash_sha="$(cat "$stash_file")"
        if [ -n "$stash_sha" ]; then
          git stash apply "$stash_sha" >/dev/null 2>&1 || true
        fi
      fi

      echo -e "\n${C_GREEN}${C_BOLD}🎉 100% SUKSES! Seluruh file telah dikembalikan ke kondisi tepat sebelum AI mulai koding!${C_RESET}\n"
      return 0
    fi
  fi

  # Fallback to Tar Archive restore
  local target="${1:-}"
  if [ -z "$target" ]; then
    target=$(ls -t "$SNAPSHOT_DIR"/*.tar.gz 2>/dev/null | head -n 1 || true)
    if [ -z "$target" ]; then
      echo -e "${C_RED}❌ Tidak ada checkpoint / snapshot yang ditemukan untuk di-rollback!${C_RESET}"
      exit 1
    fi
  else
    if [ ! -f "$target" ] && [ -f "$SNAPSHOT_DIR/$target" ]; then
      target="$SNAPSHOT_DIR/$target"
    elif [ ! -f "$target" ] && [ -f "$SNAPSHOT_DIR/${target}.tar.gz" ]; then
      target="$SNAPSHOT_DIR/${target}.tar.gz"
    fi
  fi

  echo -e "${C_CYAN}📦 Memulihkan dari archive: $(basename "$target")...${C_RESET}"
  tar -xzf "$target"
  echo -e "\n${C_GREEN}${C_BOLD}🎉 ROLLBACK SELESAI! Seluruh kode telah dipulihkan ke kondisi snapshot archive.${C_RESET}\n"
}

function list_snapshots() {
  echo -e "${C_CYAN}${C_BOLD}========================================================================${C_RESET}"
  echo -e "${C_YELLOW}${C_BOLD}📸 [TIME-TRAVEL CHECKPOINTS] Daftar Snapshot & Riwayat${C_RESET}"
  echo -e "${C_CYAN}${C_BOLD}========================================================================${C_RESET}\n"

  if [ "$IS_GIT_REPO" = true ]; then
    echo -e "${C_BOLD}🌿 Git Checkpoints:${C_RESET}"
    local git_cps
    git_cps="$(git branch --list "freebuff_cp_*" 2>/dev/null || true)"
    if [ -n "$git_cps" ]; then
      echo "$git_cps" | sed 's/^[ *]*/  • /'
    else
      echo -e "  ${C_DIM}(Belum ada git checkpoint. Dibuat otomatis saat 'freebuff-power start')${C_RESET}"
    fi
    echo ""
  fi

  echo -e "${C_BOLD}📁 Tar Snapshots:${C_RESET}"
  local count=0
  for f in "$SNAPSHOT_DIR"/*.tar.gz; do
    if [ -f "$f" ]; then
      count=$((count+1))
      local base size
      base="$(basename "$f" .tar.gz)"
      size="$(du -h "$f" | cut -f1)"
      echo -e "  • ${C_GREEN}$base${C_RESET} ${C_YELLOW}($size)${C_RESET}"
    fi
  done
  if [ "$count" -eq 0 ]; then
    echo -e "  ${C_DIM}(Tidak ada file archive tar)${C_RESET}"
  fi

  echo -e "\n👉 Untuk membatalkan kesalahan AI: ${C_GREEN}${C_BOLD}freebuff-power rollback${C_RESET}\n"
}

ACTION="${1:-list}"
shift || true

case "$ACTION" in
  save|create)
    save_snapshot "$@"
    ;;
  list)
    list_snapshots
    ;;
  restore|rollback)
    restore_snapshot "$@"
    ;;
  *)
    echo "Penggunaan: freebuff-power snapshot [save <label> | list | restore]"
    ;;
esac
