#!/usr/bin/env node
// ==============================================================================
// 🧠 FREEBUFF-POWER COMPACT REPOSITORY CONTEXT INGESTOR
// Compiles repo architecture, AST exports, and schemas into .freebuff/CONTEXT.md
// Saves up to 60% LLM tokens during multi-turn agent coding.
// ==============================================================================
const fs = require("fs");
const path = require("path");

const cwd = process.cwd();
const outDir = path.join(cwd, ".freebuff");
const outFile = path.join(outDir, "CONTEXT.md");

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

console.log("\x1b[36m\x1b[1m========================================================================\x1b[0m");
console.log("\x1b[33m\x1b[1m🧠 [FREEBUFF CONTEXT] Ingesting Codebase Architecture into Context\x1b[0m");
console.log("\x1b[36m\x1b[1m========================================================================\x1b[0m\n");

const IGNORE = new Set(["node_modules", ".git", "dist", "build", ".next", ".cache", "coverage", "__pycache__"]);
let totalFiles = 0;
const fileTree = [];
const signatures = [];

function walk(dir, depth = 0) {
  if (depth > 5) return;
  let items;
  try {
    items = fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    return;
  }

  for (const item of items) {
    if (IGNORE.has(item.name) || item.name.startsWith(".")) continue;
    const full = path.join(dir, item.name);
    const rel = path.relative(cwd, full);

    if (item.isDirectory()) {
      fileTree.push(`${"  ".repeat(depth)}📁 ${item.name}/`);
      walk(full, depth + 1);
    } else if (item.isFile()) {
      totalFiles++;
      fileTree.push(`${"  ".repeat(depth)}📄 ${item.name}`);
      extractSignatures(full, rel);
    }
  }
}

function extractSignatures(full, rel) {
  const ext = path.extname(full).toLowerCase();
  if (![".js", ".ts", ".jsx", ".tsx", ".py", ".go"].includes(ext)) return;

  try {
    const lines = fs.readFileSync(full, "utf8").split(/\r?\n/);
    const fileSigs = [];

    lines.forEach((l) => {
      const line = l.trim();
      // TS / JS exports & functions
      if (/^(export\s+(async\s+)?function|export\s+(default\s+)?(class|interface|type)|export\s+const\s+[a-zA-Z0-9_]+\s*=)/.test(line)) {
        fileSigs.push(line.replace(/\{.*$/, "").trim());
      }
      // Python def / class
      else if (/^(def\s+[a-zA-Z0-9_]+\(.*\):|class\s+[a-zA-Z0-9_]+(\(.*\))?:)/.test(line)) {
        fileSigs.push(line);
      }
      // Go func / type
      else if (/^(func\s+(\([^\)]+\)\s+)?[a-zA-Z0-9_]+\(.*\)|type\s+[a-zA-Z0-9_]+\s+struct)/.test(line)) {
        fileSigs.push(line.replace(/\{.*$/, "").trim());
      }
    });

    if (fileSigs.length > 0) {
      signatures.push({ file: rel, sigs: fileSigs.slice(0, 10) });
    }
  } catch (e) {}
}

walk(cwd);

let doc = `# Repository Architectural Context\n\n`;
doc += `> Auto-generated by Freebuff-Power on ${new Date().toISOString()}.\n`;
doc += `> Total Files Analyzed: ${totalFiles}\n\n`;

doc += `## Directory Structure\n\`\`\`text\n`;
doc += fileTree.slice(0, 80).join("\n") + "\n";
if (fileTree.length > 80) doc += `... [and ${fileTree.length - 80} more entries]\n`;
doc += `\`\`\`\n\n`;

if (signatures.length > 0) {
  doc += `## Exported Interfaces & API Boundaries\n\n`;
  signatures.slice(0, 25).forEach(s => {
    doc += `### \`${s.file}\`\n\`\`\`text\n`;
    doc += s.sigs.join("\n") + "\n";
    doc += `\`\`\`\n\n`;
  });
}

fs.writeFileSync(outFile, doc, "utf8");
console.log(`✅ Konteks repository berhasil dipadatkan ke \x1b[36m${outFile}\x1b[0m`);
console.log(`⚡ Token LLM hemat hingga 60% — agen Freebuff dapat langsung membaca file ini.\n`);
