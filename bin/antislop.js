#!/usr/bin/env node
// ==============================================================================
// 🧹 FREEBUFF-POWER ANTI-SLOP AI CODEBASE PURGER & QUALITY AUDITOR
// ==============================================================================
const fs = require("fs");
const path = require("path");

const args = process.argv.slice(2);
const shouldFix = args.includes("--fix");
const targetDir = args.find(a => !a.startsWith("-")) || process.cwd();

console.log("\x1b[36m\x1b[1m========================================================================\x1b[0m");
console.log("\x1b[35m\x1b[1m🛡️  FREEBUFF-POWER ANTI-SLOP AI PURGER & CODE QUALITY AUDITOR\x1b[0m");
console.log(`\x1b[90mTarget: ${targetDir} | Mode: ${shouldFix ? "AUTOMATIC PURGE & FIX" : "SCAN & REPORT"}\x1b[0m`);
console.log("\x1b[36m\x1b[1m========================================================================\x1b[0m\n");

const IGNORED_DIRS = new Set([
  "node_modules", ".git", ".next", "dist", "build", ".cache", "coverage",
  "vendor", ".turbo", "__pycache__", ".venv", "venv", ".idea", ".vscode"
]);

const EXTENSIONS = new Set([
  ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs",
  ".py", ".go", ".rs", ".java", ".c", ".cpp", ".cs", ".php",
  ".rb", ".swift", ".kt", ".lua", ".sh", ".bash"
]);

const SLOP_PATTERNS = [
  {
    name: "AI Placeholder Stubs (TODO / Implement Later)",
    regex: /(\/\/\s*TODO:\s*(implement|fill|add|replace|finish)\b.*|\/\*\s*TODO:\s*(implement|fill|add)\b.*?\*\/|#\s*TODO:\s*(implement|add|fill)\b.*)/gi,
    severity: "CRITICAL",
    cleanable: false
  },
  {
    name: "AI Lazy Ellipsis Shortcut (... remaining code)",
    regex: /(\/\/\s*\.{3}\s*(rest of|remaining|existing|other).*|\/\*\s*\.{3}\s*(rest of|remaining|existing|other).*?\*\/|#\s*\.{3}\s*(rest of|remaining).*)/gi,
    severity: "CRITICAL",
    cleanable: false
  },
  {
    name: "Unimplemented Stub Functions",
    regex: /(throw\s+new\s+Error\s*\(\s*["'](Not implemented|TODO|implement later)["']\s*\)|raise\s+NotImplementedError\s*\(\s*["'](TODO|implement)["']\s*\))/gi,
    severity: "HIGH",
    cleanable: false
  },
  {
    name: "Obvious AI Comment Bloat (e.g. '// return the result')",
    regex: /(\/\/\s*(return\s+the\s+(result|response|value)|increment\s+i|create\s+a\s+new\s+instance|call\s+the\s+function|export\s+the\s+module|import\s+dependencies)\b.*$)/gim,
    severity: "MEDIUM",
    cleanable: true
  },
  {
    name: "AI Sycophantic / Chatbot Header Comments",
    regex: /(\/\/\s*(Here is the (updated|complete|fixed) code|This file was generated by|AI Assistant:).*$)/gim,
    severity: "HIGH",
    cleanable: true
  },
  {
    name: "Codebuff / Freebuff / Bot Commit Watermarks",
    regex: /(Co-Authored-By:.*(codebuff|freebuff|manicode)|🤖\s*Generated with (Codebuff|Freebuff)|<!--.*watermark.*-->)/gim,
    severity: "CRITICAL",
    cleanable: true
  }
];

let filesScanned = 0;
let totalSlopFindings = 0;
const findingsByFile = [];

function walkDir(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (e) {
    return;
  }

  for (const entry of entries) {
    if (IGNORED_DIRS.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      walkDir(fullPath);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (EXTENSIONS.has(ext) || entry.name.endsWith(".md")) {
        scanFile(fullPath);
      }
    }
  }
}

function scanFile(filePath) {
  filesScanned++;
  let content;
  try {
    content = fs.readFileSync(filePath, "utf8");
  } catch (e) {
    return;
  }

  let fileModified = false;
  let lines = content.split(/\r?\n/);
  const fileIssues = [];

  SLOP_PATTERNS.forEach((pattern) => {
    const regex = new RegExp(pattern.regex.source, pattern.regex.flags);
    
    lines.forEach((line, index) => {
      if (regex.test(line)) {
        fileIssues.push({
          lineNum: index + 1,
          lineText: line.trim(),
          rule: pattern.name,
          severity: pattern.severity,
          cleanable: pattern.cleanable
        });
        totalSlopFindings++;
      }
    });

    if (shouldFix && pattern.cleanable) {
      const prevLength = content.length;
      content = content.replace(regex, "");
      if (content.length !== prevLength) {
        fileModified = true;
      }
    }
  });

  if (fileIssues.length > 0) {
    findingsByFile.push({
      file: path.relative(process.cwd(), filePath),
      issues: fileIssues
    });
  }

  if (shouldFix && fileModified) {
    const cleaned = content.replace(/\n{3,}/g, "\n\n");
    fs.writeFileSync(filePath, cleaned, "utf8");
  }
}

walkDir(targetDir);

if (findingsByFile.length === 0) {
  console.log(`\x1b[32m\x1b[1m✨ SELAMAT! Codebase 100% BERSIH dari AI Slop, placeholder stubs, dan watermark (${filesScanned} file dipindai).\x1b[0m\n`);
  process.exit(0);
}

console.log(`\x1b[33m\x1b[1m⚠️  Ditemukan ${totalSlopFindings} indikasi AI-Slop pada ${findingsByFile.length} file:\x1b[0m\n`);

findingsByFile.forEach((entry) => {
  console.log(`\x1b[1m📄 ${entry.file}\x1b[0m`);
  entry.issues.forEach((iss) => {
    const sevColor = iss.severity === "CRITICAL" ? "\x1b[31m" : iss.severity === "HIGH" ? "\x1b[33m" : "\x1b[90m";
    console.log(`   ${sevColor}[${iss.severity}]\x1b[0m Baris ${iss.lineNum}: ${iss.rule}`);
    console.log(`     \x1b[90m"${iss.lineText.substring(0, 80)}"\x1b[0m`);
  });
  console.log("");
});

if (shouldFix) {
  console.log("\x1b[32m\x1b[1m✅ Seluruh watermark dan komentar AI bloat yang dapat dibersihkan otomatis telah dibersihkan!\x1b[0m");
  console.log("\x1b[33m👉 Catatan: Untuk [CRITICAL] placeholder stubs, silakan lengkapi logika bisnis sebenarnya.\x1b[0m\n");
} else {
  console.log("\x1b[36m💡 TIPS:\x1b[0m Jalankan \x1b[1mfreebuff-power antislop --fix\x1b[0m untuk membersihkan komentar bloat & watermark otomatis.\n");
}
