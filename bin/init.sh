#!/usr/bin/env bash
# ==============================================================================
# 🧰 FREEBUFF-POWER SUPERPOWER INJECTOR (AGENTS.MD & .FREEBUFF COPY ENGINE)
# ==============================================================================
set -euo pipefail

SOURCE="${BASH_SOURCE[0]}"
while [ -h "$SOURCE" ]; do
  DIR="$( cd -P "$( dirname "$SOURCE" )" >/dev/null 2>&1 && pwd )"
  SOURCE="$(readlink "$SOURCE")"
  [[ $SOURCE != /* ]] && SOURCE="$DIR/$SOURCE"
done
SCRIPT_DIR="$( cd -P "$( dirname "$SOURCE" )" >/dev/null 2>&1 && pwd )"

TARGET_DIR="${1:-.}"
mkdir -p "$TARGET_DIR"

GLOBAL_SUPERPOWER_DIR="$HOME/.freebuff-superpower"
LOCAL_SUPERPOWER_DIR="$SCRIPT_DIR/../superpower"

SOURCE_SUPERPOWER=""
if [ -d "$LOCAL_SUPERPOWER_DIR" ] && [ -f "$LOCAL_SUPERPOWER_DIR/AGENTS.md" ]; then
  SOURCE_SUPERPOWER="$LOCAL_SUPERPOWER_DIR"
elif [ -d "$GLOBAL_SUPERPOWER_DIR" ] && [ -f "$GLOBAL_SUPERPOWER_DIR/AGENTS.md" ]; then
  SOURCE_SUPERPOWER="$GLOBAL_SUPERPOWER_DIR"
fi

if [ -n "$SOURCE_SUPERPOWER" ]; then
  # Copy AGENTS.md
  cp -f "$SOURCE_SUPERPOWER/AGENTS.md" "$TARGET_DIR/AGENTS.md"
  
  # Inject .agents standard folder (Native Freebuff & Codebuff standard)
  mkdir -p "$TARGET_DIR/.agents/skills" "$TARGET_DIR/.agents/agents" "$TARGET_DIR/.agents/rules"
  if [ -d "$SOURCE_SUPERPOWER/skills" ]; then
    cp -rf "$SOURCE_SUPERPOWER/skills/"* "$TARGET_DIR/.agents/skills/" 2>/dev/null || true
  fi
  if [ -d "$SOURCE_SUPERPOWER/agents" ]; then
    cp -rf "$SOURCE_SUPERPOWER/agents/"* "$TARGET_DIR/.agents/agents/" 2>/dev/null || true
  fi
  if [ -d "$SOURCE_SUPERPOWER/rules" ]; then
    cp -rf "$SOURCE_SUPERPOWER/rules/"* "$TARGET_DIR/.agents/rules/" 2>/dev/null || true
  fi

  # Maintain backward compatibility for .freebuff/
  mkdir -p "$TARGET_DIR/.freebuff/agents" "$TARGET_DIR/.freebuff/skills"
  if [ -d "$TARGET_DIR/.agents/skills" ]; then
    cp -rf "$TARGET_DIR/.agents/skills/"* "$TARGET_DIR/.freebuff/skills/" 2>/dev/null || true
  fi
  if [ -d "$TARGET_DIR/.agents/agents" ]; then
    cp -rf "$TARGET_DIR/.agents/agents/"* "$TARGET_DIR/.freebuff/agents/" 2>/dev/null || true
  fi

  # Ensure user home ~/.agents/skills/ is also globally populated
  mkdir -p "$HOME/.agents/skills" "$HOME/.agents/agents" "$HOME/.agents/rules" 2>/dev/null || true
  if [ -d "$SOURCE_SUPERPOWER/skills" ]; then
    cp -rf "$SOURCE_SUPERPOWER/skills/"* "$HOME/.agents/skills/" 2>/dev/null || true
  fi

  # Auto-inject stealth git hooks into project repository
  REPO_ROOT="$TARGET_DIR"
  if [ ! -d "$REPO_ROOT/.git" ]; then
    REPO_ROOT="$(git -C "$TARGET_DIR" rev-parse --show-toplevel 2>/dev/null || echo "")"
  fi
  if [ -n "$REPO_ROOT" ] && [ -d "$REPO_ROOT/.git" ]; then
    mkdir -p "$REPO_ROOT/.git/hooks"
    cat << 'HOOK_EOF' > "$REPO_ROOT/.git/hooks/prepare-commit-msg"
#!/usr/bin/env bash
COMMIT_MSG_FILE="$1"
[ -f "$COMMIT_MSG_FILE" ] || exit 0
sed -i -E '/Co-Authored-By:.*(codebuff|freebuff|manicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/(Generated with|Generated by|🤖).*([Cc]odebuff|[Ff]reebuff|[Mm]anicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/<!--.*watermark.*-->/Id' "$COMMIT_MSG_FILE"
HOOK_EOF

    cat << 'HOOK_EOF' > "$REPO_ROOT/.git/hooks/commit-msg"
#!/usr/bin/env bash
COMMIT_MSG_FILE="$1"
[ -f "$COMMIT_MSG_FILE" ] || exit 0
sed -i -E '/Co-Authored-By:.*(codebuff|freebuff|manicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/(Generated with|Generated by|🤖).*([Cc]odebuff|[Ff]reebuff|[Mm]anicode)/Id' "$COMMIT_MSG_FILE"
HOOK_EOF

    cat << 'HOOK_EOF' > "$REPO_ROOT/.git/hooks/pre-push"
#!/usr/bin/env bash
LEAKS=0
check_pattern() {
  local pattern="$1"
  local desc="$2"
  local matches
  matches=$(git diff origin/main..HEAD 2>/dev/null | grep -E "^\+" | grep -E "$pattern" || true)
  if [ -n "$matches" ]; then
    echo -e "\033[0;31m[CRITICAL LEAK DETECTED] $desc\033[0m"
    LEAKS=$((LEAKS + 1))
  fi
}
check_pattern "(ghp_[a-zA-Z0-9]{36}|github_pat_[a-zA-Z0-9_]{82})" "GitHub Personal Access Token"
check_pattern "(AKIA[0-9A-Z]{16})" "AWS Access Key ID"
check_pattern "-----BEGIN (RSA|EC|OPENSSH|DSA) PRIVATE KEY-----" "Private Key / PEM Certificate"
check_pattern "manicode-[a-zA-Z0-9]{32,}" "Freebuff / Manicode Auth Bearer Token"
if [ "$LEAKS" -gt 0 ]; then
  echo -e "\033[0;31m\033[1m❌ Git push dibatalkan karena terdeteksi potensi secret leak!\033[0m"
  exit 1
fi
exit 0
HOOK_EOF

    chmod +x "$REPO_ROOT/.git/hooks/prepare-commit-msg" "$REPO_ROOT/.git/hooks/commit-msg" "$REPO_ROOT/.git/hooks/pre-push" 2>/dev/null || true
  fi
  
  echo -e "\n\033[0;36m\033[1m========================================================================\033[0m"
  echo -e "\033[0;32m\033[1m🎉 INJEKSI SUKSES 100%! AGENTS.MD & .AGENTS/ TELAH TERPASANG LENGKAP\033[0m"
  echo -e "\033[0;36m\033[1m========================================================================\033[0m"
  echo -e "📁 Target Folder  : \033[0;33m$TARGET_DIR\033[0m"
  echo -e "👥 Sub-Agents     : \033[0;32m83 Specialized Production Agents (.agents/agents/)\033[0m"
  echo -e "🧰 Modular Skills : \033[0;32m561 Curated Skills (.agents/skills/)\033[0m"
  echo -e "📜 Stack Rules    : \033[0;32m23 Language & Framework Rules (.agents/rules/)\033[0m"
  echo -e "🛡️ Stealth Hooks  : \033[0;32mGit Watermark Purge & Pre-Push Secret Guard Active\033[0m"
  echo -e "\n\033[1m💡 CARA MEMANGGIL DI CLI FREEBUFF:\033[0m"
  echo -e "👉 \033[0;32m\033[1mDi prompt terminal Freebuff, ketik:\033[0m"
  echo -e "   \033[0;36m\033[1m@AGENTS.md <instruksi koding kamu>\033[0m"
  echo -e "   Contoh: \033[0;33m@AGENTS.md buatkan REST API auth JWT + PostgreSQL\033[0m"
  echo -e "   Contoh: \033[0;33m@AGENTS.md /plan arsitektur microservices\033[0m"
  echo -e "   Contoh: \033[0;33m@AGENTS.md /ui rancang dashboard Next.js 15 Tailwind v4\033[0m"
  echo -e "\033[0;36m\033[1m========================================================================\033[0m\n"
else
  echo -e "\033[0;31m❌ Gagal menemukan template Superpower di $GLOBAL_SUPERPOWER_DIR\033[0m"
  exit 1
fi
