#!/usr/bin/env bash
# ==============================================================================
# 🧰 FREEBUFF-POWER SUPERPOWER INJECTOR (AGENTS.MD & .FREEBUFF COPY ENGINE)
# ==============================================================================
set -euo pipefail

SOURCE="${BASH_SOURCE[0]}"
while [ -h "$SOURCE" ]; do
  DIR="$( cd -P "$( dirname "$SOURCE" )" >/dev/null 2>&1 && pwd )"
  SOURCE="$(readlink "$SOURCE")"
  [[ $SOURCE != /* ]] && SOURCE="$DIR/$SOURCE"
done
SCRIPT_DIR="$( cd -P "$( dirname "$SOURCE" )" >/dev/null 2>&1 && pwd )"

TARGET_DIR="${1:-.}"
mkdir -p "$TARGET_DIR"

GLOBAL_SUPERPOWER_DIR="$HOME/.freebuff-superpower"
LOCAL_SUPERPOWER_DIR="$SCRIPT_DIR/../superpower"

SOURCE_SUPERPOWER=""
if [ -d "$LOCAL_SUPERPOWER_DIR" ] && [ -f "$LOCAL_SUPERPOWER_DIR/AGENTS.md" ]; then
  SOURCE_SUPERPOWER="$LOCAL_SUPERPOWER_DIR"
elif [ -d "$GLOBAL_SUPERPOWER_DIR" ] && [ -f "$GLOBAL_SUPERPOWER_DIR/AGENTS.md" ]; then
  SOURCE_SUPERPOWER="$GLOBAL_SUPERPOWER_DIR"
fi

if [ -n "$SOURCE_SUPERPOWER" ]; then
  # Copy AGENTS.md
  cp -f "$SOURCE_SUPERPOWER/AGENTS.md" "$TARGET_DIR/AGENTS.md"
  
  # Copy .freebuff folder (agents & skills)
  mkdir -p "$TARGET_DIR/.freebuff/agents" "$TARGET_DIR/.freebuff/skills"
  if [ -d "$SOURCE_SUPERPOWER/.freebuff" ]; then
    cp -rf "$SOURCE_SUPERPOWER/.freebuff/"* "$TARGET_DIR/.freebuff/"
  fi

  # Auto-inject stealth git hooks into project repository
  REPO_ROOT="$TARGET_DIR"
  if [ ! -d "$REPO_ROOT/.git" ]; then
    REPO_ROOT="$(git -C "$TARGET_DIR" rev-parse --show-toplevel 2>/dev/null || echo "")"
  fi
  if [ -n "$REPO_ROOT" ] && [ -d "$REPO_ROOT/.git" ]; then
    mkdir -p "$REPO_ROOT/.git/hooks"
    cat << 'HOOK_EOF' > "$REPO_ROOT/.git/hooks/prepare-commit-msg"
#!/usr/bin/env bash
COMMIT_MSG_FILE="$1"
[ -f "$COMMIT_MSG_FILE" ] || exit 0
sed -i -E '/Co-Authored-By:.*(codebuff|freebuff|manicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/(Generated with|Generated by|🤖).*([Cc]odebuff|[Ff]reebuff|[Mm]anicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/<!--.*watermark.*-->/Id' "$COMMIT_MSG_FILE"
HOOK_EOF

    cat << 'HOOK_EOF' > "$REPO_ROOT/.git/hooks/commit-msg"
#!/usr/bin/env bash
COMMIT_MSG_FILE="$1"
[ -f "$COMMIT_MSG_FILE" ] || exit 0
sed -i -E '/Co-Authored-By:.*(codebuff|freebuff|manicode)/Id' "$COMMIT_MSG_FILE"
sed -i -E '/(Generated with|Generated by|🤖).*([Cc]odebuff|[Ff]reebuff|[Mm]anicode)/Id' "$COMMIT_MSG_FILE"
HOOK_EOF

    chmod +x "$REPO_ROOT/.git/hooks/prepare-commit-msg" "$REPO_ROOT/.git/hooks/commit-msg" 2>/dev/null || true
  fi
  
  echo -e "\033[0;32m\033[1m[✓] Sukses menginjeksi AGENTS.md, .freebuff/ & Stealth Git Hooks ke $TARGET_DIR\033[0m"
else
  echo -e "\033[0;31m❌ Gagal menemukan template Superpower di $GLOBAL_SUPERPOWER_DIR\033[0m"
  exit 1
fi
